using System.Globalization;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Fonlow.ErpNext;

/// <summary>
/// ERPNext datetime is local time of default timezone in "Settings/System Settings" of ERPNext site.
/// </summary>
public class ErpNextDateTimeConverter : JsonConverter<DateTime> //generated by copilot
{
    private const string ErpNextFormat = "yyyy-MM-dd HH:mm:ss.ffffff";
    private const string ErpNextFormatShort = "yyyy-MM-dd HH:mm:ss";
    readonly TimeZoneInfo localTimeZone;

    public ErpNextDateTimeConverter(TimeZoneInfo timeZone)
    {
        localTimeZone = timeZone;
    }
    public override DateTime Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
    {
        string raw = reader.GetString();

        if (DateTime.TryParseExact(raw, ErpNextFormat, CultureInfo.InvariantCulture, DateTimeStyles.AssumeLocal, out DateTime localTime))
        {
            DateTime localDateTime = DateTime.SpecifyKind(localTime, DateTimeKind.Unspecified);
            DateTime utcTime = TimeZoneInfo.ConvertTimeToUtc(localDateTime, localTimeZone);
            return utcTime;
        }

        if (DateTime.TryParseExact(raw, ErpNextFormatShort, CultureInfo.InvariantCulture, DateTimeStyles.AssumeLocal, out localTime))
        {
            DateTime localDateTime = DateTime.SpecifyKind(localTime, DateTimeKind.Unspecified);
            DateTime utcTime = TimeZoneInfo.ConvertTimeToUtc(localDateTime, localTimeZone);
            return utcTime;
        }

        throw new JsonException($"Invalid ERPNext datetime format: {raw}");
    }

    public override void Write(Utf8JsonWriter writer, DateTime value, JsonSerializerOptions options)
    {
        // Convert UTC to local DateTime for serialization
        DateTime localDateTime = TimeZoneInfo.ConvertTimeFromUtc(value, localTimeZone);
        writer.WriteStringValue(localDateTime.ToString(ErpNextFormat));
    }
}